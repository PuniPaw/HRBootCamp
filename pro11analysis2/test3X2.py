#   적합도 검정
# : 자연현상이나 각종실험을 통해 관찰되는 도수들이 귀무가설 하의 분포(범주형 자료의 각 수준별비율)에 
#   얼마나 일치하는가에 대한 분석을 적합도 검정이라 한다.
# : 관측값들이 어떤 이론적 분포를 따르고 있는지를 검정으로 한 개의 요인을 대상으로 함.

# <적합도 검정(goodness of fit test) 실습>
# 주사위를 60회 던져서 나온 관측도수/기대도수가 아래와 같이 나온 경우에 
# 이 주사위는 일반적인 게임에 적합한 주사위가 맞는가를 일원카이제곱 검정으로 분석하자.

# 귀무 가설 : 기대치와 관찰치는 차이가 없다. 이 주사위는 게임에 적합하다.
# 대립 가설 : 기대치와 관찰치는 차이가 있다. 이 주사위는 게임에 적합하지 않다.

import pandas as pd
import scipy.stats as stats

data = [4, 6, 17, 16, 8, 9]   #  각 눈금에 대한 관측 빈도 수
print(stats.chisquare(data))

alpha = 0.05
results = stats.chisquare(data)
print(f"카이제곱 검정 통계량 : {results.statistic:.4f}")   # 14.2000
print(f"유의확률(P-value) : {results.pvalue:.4f}")    #  0.0144

if results.pvalue < alpha : 
    print("판정 : 귀무가설 기각(통계적으로 유의함)")
else:
    print("판정 : 귀무가설 채택(통계적으로 유의하지 않음)")

# 판정 : 유의수준0.05 > pvalue 0.0144 이므로 귀무가설을 기각하고 대립가설을 채택.
# 검정에 사용된 데이터는 우연히 발생한 것이 아니라 필연적인 원인에 의해 발생한 것이다.
# 이 주사위는 게임에 적합하지 않다. 라는 의견을 받아 들임.

